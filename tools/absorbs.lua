-- Writes Data/Absorbs.lua: every spell in WoW: Forever's spell data whose aura says it absorbs
-- damage ("Absorbs $w1 Fire damage.", "absorbing $s1 damage"), as the aura container's
-- includeSpellIDs map. Reads the newest ../.spelldata/wowf/<version>/ with a Spell.csv
-- (../.spelldata/fetch.sh refreshes it). Run from the repository root with Lua 5.1:
--
--   lua tools/absorbs.lua

package.path = "./?.lua;" .. package.path
local lfs = require("lfs")
local sh = require("tests.sh")

local DATA = "../.spelldata/wowf"
local OUT = "Data/Absorbs.lua"

---The newest version folder with the files needed.
---@return string
local function Newest()
    local best
    for entry in lfs.dir(DATA) do
        if entry:match("^%d") and sh.exists(DATA .. "/" .. entry .. "/Spell.csv") then
            if not best or entry > best then best = entry end
        end
    end
    return assert(best, "no Spell.csv under " .. DATA)
end

---A CSV file's records, each a list of fields. Quoted fields may hold commas, line breaks, and ""
---for a quote, so the text is read as a whole rather than by line.
---@param text string
---@return string[][]
local function Records(text)
    local records, fields, i, n = {}, {}, 1, #text
    while i <= n do
        local value
        if text:sub(i, i) == '"' then
            local parts, j = {}, i + 1
            while true do
                local q = assert(text:find('"', j, true), "unclosed quote")
                parts[#parts + 1] = text:sub(j, q - 1)
                if text:sub(q + 1, q + 1) == '"' then
                    parts[#parts + 1], j = '"', q + 2
                else
                    i = q + 1
                    break
                end
            end
            value = table.concat(parts)
        else
            local stop = text:find("[,\r\n]", i) or n + 1
            value, i = text:sub(i, stop - 1), stop
        end
        fields[#fields + 1] = value
        local sep = text:sub(i, i)
        if sep == "," then
            i = i + 1
        else
            records[#records + 1], fields = fields, {}
            i = i + (text:sub(i, i + 1) == "\r\n" and 2 or 1)
        end
    end
    return records
end

---A CSV file's rows, each by column name.
---@param path string
---@return table[]
local function Rows(path)
    local records = Records(sh.read(path))
    local header, rows = records[1], {}
    for r = 2, #records do
        local row = {}
        for k, name in ipairs(header) do
            row[name] = records[r][k]
        end
        rows[#rows + 1] = row
    end
    return rows
end

local version = Newest()
local dir = DATA .. "/" .. version .. "/"
local names = {}
for _, row in ipairs(Rows(dir .. "SpellName.csv")) do
    names[tonumber(row.ID)] = row.Name_lang
end

local ids = {}
for _, row in ipairs(Rows(dir .. "Spell.csv")) do
    local aura = (row.AuraDescription_lang or ""):lower()
    if aura:find("absorb") and aura:find("damage") then ids[#ids + 1] = tonumber(row.ID) end
end
table.sort(ids)

local lines = {
    "-- Generated by tools/absorbs.lua from WoW: Forever's spell data " .. version .. ": every spell whose",
    "-- aura says it absorbs damage, as the aura container's includeSpellIDs map. Run the tool again",
    "-- rather than editing this file.",
    "",
    "local _, ns = ... ---@type string, AddonNamespace",
    "",
    "-- stylua: ignore start",
    "ns.absorbSpells = {",
}
for _, id in ipairs(ids) do
    lines[#lines + 1] = ("    [%d] = true, -- %s"):format(id, names[id] or "?")
end
lines[#lines + 1] = "}"
lines[#lines + 1] = "-- stylua: ignore end"
local handle = assert(io.open(OUT, "wb"))
handle:write(table.concat(lines, "\n"), "\n")
handle:close()
print(("%s: %d spells from %s"):format(OUT, #ids, version))
